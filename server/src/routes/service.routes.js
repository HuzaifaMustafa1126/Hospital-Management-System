import { Router } from 'express';
import { serviceController } from '../controllers/service.controller.js';
import { authenticate, requirePermission } from '../middleware/auth.middleware.js';
import { asyncHandler } from '../utils/async-handler.js';
export const serviceRouter = Router();
serviceRouter.use(authenticate);
serviceRouter.get('/', requirePermission('SERVICE_VIEW'), asyncHandler(serviceController.list));
serviceRouter.get('/analytics', requirePermission('SERVICE_VIEW'), asyncHandler(serviceController.analytics));
serviceRouter.get('/:id/deletion-impact', requirePermission('SERVICE_DELETE'), asyncHandler(serviceController.deletionImpact));
serviceRouter.get('/:id', requirePermission('SERVICE_VIEW'), asyncHandler(serviceController.get));
serviceRouter.post('/', requirePermission('SERVICE_CREATE','SERVICE_MANAGE_PRICING','SERVICE_ASSIGN_DEPARTMENTS'), asyncHandler(serviceController.create));
serviceRouter.patch('/:id', requirePermission('SERVICE_UPDATE'), asyncHandler(serviceController.update));
serviceRouter.patch('/:id/status', requirePermission('SERVICE_CHANGE_STATUS'), asyncHandler(serviceController.status));
serviceRouter.delete('/:id', requirePermission('SERVICE_DELETE'), asyncHandler(serviceController.remove));
